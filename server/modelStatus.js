// ============================================================================
// FINE-TUNED MODEL STATUS — measured, never declared.
//
// Everything this module reports is read from the filesystem, from the OS, or
// from the inference service itself. Nothing here is derived from an
// environment variable that merely contains a model name: `INSAF_MODEL` is
// never consulted, because a name in the environment proves only that someone
// typed a name.
//
// The distinction it exists to keep visible:
//   * adapter files on disk        -> a training run produced weights
//   * base weights in the cache    -> the model those weights attach to exists locally
//   * service reports modelLoaded  -> a process actually holds the merged model in memory
//   * inference test passed        -> text was actually generated by that model
// Each of the four is answered separately and each is false unless measured.
// ============================================================================

import fs from 'fs';
import os from 'os';
import path from 'path';
import { spawnSync } from 'child_process';
import { fileURLToPath } from 'url';
import { loraEnabled, loraServiceConfigured, loraHealth } from './loraProvider.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(HERE, '..');
const OUTPUT_ROOT = path.join(REPO, 'training', 'output');
const HF_CACHE = process.env.HF_CACHE_DIR || 'D:/hf-cache';

// Probing python/nvidia-smi costs seconds; the answer does not change while the
// server runs. Cached, with a bounded TTL so a service that comes online later
// is picked up.
const TTL_MS = 5 * 60 * 1000;
let cached = null;

const YESNO = (v) => (v ? 'YES' : 'NO');

/** The safetensors header only — the 161 MB of weights are never loaded here. */
function safetensorsHeader(file) {
  let fd = null;
  try {
    fd = fs.openSync(file, 'r');
    const lenBuf = Buffer.alloc(8);
    if (fs.readSync(fd, lenBuf, 0, 8, 0) !== 8) return null;
    const headerLen = lenBuf.readUInt32LE(0) + Number(lenBuf.readUInt32LE(4)) * 4294967296;
    if (!Number.isFinite(headerLen) || headerLen < 2 || headerLen > 64 * 1024 * 1024) return null;
    const head = Buffer.alloc(headerLen);
    if (fs.readSync(fd, head, 0, headerLen, 8) !== headerLen) return null;
    const json = JSON.parse(head.toString('utf8'));
    let params = 0;
    let tensors = 0;
    const dtypes = new Set();
    for (const [k, v] of Object.entries(json)) {
      if (k === '__metadata__') continue;
      tensors++;
      dtypes.add(v.dtype);
      params += (v.shape || []).reduce((a, b) => a * b, 1);
    }
    return { tensors, params, dtypes: [...dtypes], format: json.__metadata__?.format || null };
  } catch {
    return null;
  } finally {
    if (fd !== null) fs.closeSync(fd);
  }
}

/** Every adapter directory that carries a real adapter_config.json. */
function discoverAdapters() {
  const found = [];
  let entries = [];
  try {
    entries = fs.readdirSync(OUTPUT_ROOT, { withFileTypes: true });
  } catch {
    return found;
  }
  const candidates = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    candidates.push(path.join(OUTPUT_ROOT, e.name, 'adapter'));
    candidates.push(path.join(OUTPUT_ROOT, e.name));
  }
  for (const dir of candidates) {
    const cfgFile = path.join(dir, 'adapter_config.json');
    if (!fs.existsSync(cfgFile)) continue;
    let cfg = null;
    try {
      cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
    } catch {
      cfg = null;
    }
    const weights = ['adapter_model.safetensors', 'adapter_model.bin']
      .map(f => ({ f, p: path.join(dir, f) }))
      .filter(w => fs.existsSync(w.p));
    const header = weights.length && weights[0].f.endsWith('.safetensors')
      ? safetensorsHeader(weights[0].p) : null;
    found.push({
      dir: path.relative(REPO, dir).replace(/\\/g, '/'),
      baseModel: cfg ? String(cfg.base_model_name_or_path || '') : '',
      baseRevision: cfg && cfg.revision ? String(cfg.revision) : null,
      peftVersion: cfg ? (cfg.peft_version || null) : null,
      method: cfg ? (cfg.peft_type || null) : null,
      rank: cfg ? (cfg.r ?? null) : null,
      alpha: cfg ? (cfg.lora_alpha ?? null) : null,
      dropout: cfg ? (cfg.lora_dropout ?? null) : null,
      targetModules: Array.isArray(cfg?.target_modules) ? cfg.target_modules : null,
      taskType: cfg ? (cfg.task_type || null) : null,
      configFile: fs.existsSync(cfgFile),
      weightFile: weights.length ? path.basename(weights[0].p) : null,
      weightBytes: weights.length ? Number(fs.statSync(weights[0].p).size) : 0,
      tensors: header ? header.tensors : null,
      parameters: header ? header.params : null,
      dtypes: header ? header.dtypes : null,
      weightFormat: header ? header.format : null,
      tokenizerFiles: ['tokenizer.json', 'tokenizer_config.json'].filter(f => fs.existsSync(path.join(dir, f))),
      // A directory holding only a README is not a model. Recorded so the
      // distinction between "trained artifacts present" and "docs present"
      // cannot collapse later.
      readmeOnly: weights.length === 0 && !fs.existsSync(cfgFile),
    });
  }
  return found;
}

/** Are the base weights that an adapter attaches to actually on this machine? */
function baseWeightCache(repoId) {
  const out = { cacheDir: HF_CACHE.replace(/\\/g, '/'), snapshots: 0, weightFiles: 0, bytes: 0, resolved: null };
  if (!repoId) return out;
  const slug = path.join(HF_CACHE, `models--${String(repoId).replace(/\//g, '--')}`);
  out.slug = slug.replace(/\\/g, '/');
  const snapRoot = path.join(slug, 'snapshots');
  let ids = [];
  try {
    ids = fs.readdirSync(snapRoot);
  } catch {
    return out;
  }
  out.snapshots = ids.length;
  for (const id of ids) {
    let files = [];
    try {
      files = fs.readdirSync(path.join(snapRoot, id));
    } catch {
      continue;
    }
    for (const f of files) {
      if (!/\.(safetensors|bin|gguf)$/.test(f)) continue;
      let size = 0;
      try {
        size = Number(fs.statSync(path.join(snapRoot, id, f)).size);
      } catch {
        continue;
      }
      out.weightFiles++;
      out.bytes += size;
      out.resolved = `${id}/${f}`;
    }
  }
  return out;
}

function probe(cmd, args, timeoutMs) {
  try {
    const r = spawnSync(cmd, args, { encoding: 'utf8', timeout: timeoutMs, windowsHide: true });
    if (r.error) return { ok: false, error: r.error.code === 'ENOENT' ? `${cmd} is not installed` : r.error.message };
    return {
      ok: r.status === 0,
      output: String(r.stdout || r.stderr || '').trim().slice(0, 300),
      exitCode: r.status,
    };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

function hostFacts() {
  const totalMb = Math.round(os.totalmem() / 1048576);
  const freeMb = Math.round(os.freemem() / 1048576);
  const gpu = probe('nvidia-smi', ['--query-gpu=name,memory.total', '--format=csv,noheader'], 8000);
  const torch = probe('python', ['-c', 'import torch;print(torch.__version__, torch.cuda.is_available())'], 30000);
  return {
    platform: `${os.platform()} ${os.arch()} ${os.release()}`,
    cpus: os.cpus().length,
    ramTotalMb: totalMb,
    ramFreeMb: freeMb,
    cudaDevice: gpu.ok ? gpu.output : null,
    cudaAvailable: gpu.ok,
    cudaProbeError: gpu.ok ? null : (gpu.error || gpu.output || 'nvidia-smi returned a non-zero exit'),
    torchAvailable: torch.ok,
    torchProbe: torch.ok ? torch.output : null,
    torchProbeError: torch.ok ? null : (torch.error || torch.output || 'python -c "import torch" returned a non-zero exit'),
  };
}

/**
 * What a 7B model in the precision this adapter was trained at needs, computed
 * from the measured adapter rather than asserted: hidden 3584 / MLP 18944 are
 * Qwen2.5-7B shapes, so the base is the 7.61 B parameter model.
 */
function requirementsFor(adapter, host) {
  if (!adapter) return null;
  const baseParamsB = 7.61;
  const bf16Gb = Math.round(baseParamsB * 2 * 100) / 100;
  const int4Gb = Math.round(baseParamsB * 0.5 * 100) / 100;
  return {
    baseModelParametersB: baseParamsB,
    weightsInMemoryGb_bf16: bf16Gb,
    weightsInMemoryGb_int4: int4Gb,
    note: 'weights only — before KV cache, activations and the tokenizer. Adapter dtypes measured: '
      + (adapter.dtypes || []).join('/') + '.',
    hostRamTotalGb: Math.round((host.ramTotalMb / 1024) * 100) / 100,
    fitsInHostRam_bf16: (host.ramTotalMb / 1024) >= bf16Gb,
    fitsInHostRam_int4: (host.ramTotalMb / 1024) >= int4Gb,
  };
}

async function runInferenceProbe() {
  // Only ever reached when the operator has explicitly turned the provider on.
  // When it is off the honest answer is "not attempted", not a simulated pass.
  if (!loraEnabled()) {
    return {
      attempted: false,
      passed: 'NOT_ATTEMPTED',
      reason: 'The LoRA provider is disabled in this deployment, so no fine-tuned inference has been '
        + 'executed. The answer text users receive is composed by the deterministic corpus composer.',
    };
  }
  if (!loraServiceConfigured()) {
    return { attempted: false, passed: 'NO', reason: 'provider is enabled but no inference service URL is configured' };
  }
  const health = await loraHealth();
  if (!health.modelLoaded) {
    return {
      attempted: false,
      passed: 'NO',
      reason: health.reason || health.error || 'the inference service reports no loaded model',
      health,
    };
  }
  try {
    const { answerWithLora } = await import('./loraProvider.js');
    const { retrieveCorrected } = await import('./evidenceGate.js');
    const probeQuery = 'What is the penalty for theft under the Pakistan Penal Code?';
    const retrieved = await retrieveCorrected(probeQuery, { isOnline: false, maxCorrections: 0 });
    const chunks = (retrieved && retrieved.chunks) || [];
    if (!chunks.length) {
      return { attempted: true, passed: 'NO', reason: 'the probe retrieved no corpus evidence to condition on', health };
    }
    const result = await answerWithLora({ question: probeQuery, chunks: chunks.slice(0, 4), language: 'en' });
    return {
      attempted: true,
      passed: YESNO(result.ok),
      reason: result.ok ? 'one evidence-conditioned generation passed the answer contract' : result.reason,
      provider: result.provider || null,
      health,
    };
  } catch (err) {
    return { attempted: true, passed: 'NO', reason: `probe failed: ${err.message}`, health };
  }
}

/**
 * The whole picture, computed. Callers must not re-derive any of these fields
 * from configuration — that is the defect this module exists to close.
 */
export async function getModelStatus({ force = false } = {}) {
  if (cached && !force && Date.now() - cached.at < TTL_MS) return cached.value;

  const adapters = discoverAdapters();
  const loadable = adapters.filter(a => a.weightBytes > 0 && a.baseModel);
  const adapter = loadable[0] || null;
  const host = hostFacts();
  const cache = adapter ? baseWeightCache(adapter.baseModel) : { weightFiles: 0, bytes: 0 };
  const baseWeightsPresent = cache.weightFiles > 0;
  const inference = await runInferenceProbe();
  const service = inference.health || null;

  const blockers = [];
  if (!adapter) blockers.push('no adapter with real weights was found under training/output');
  if (adapter && !baseWeightsPresent) {
    blockers.push(`the base model ${adapter.baseModel} is not in the local Hugging Face cache `
      + `(${String(cache.cacheDir || '')}) — only ${cache.snapshots || 0} snapshot dir(s), `
      + `${cache.weightFiles} weight file(s)`);
  }
  if (!host.cudaAvailable) blockers.push(`no CUDA GPU: ${host.cudaProbeError}`);
  if (!host.torchAvailable) blockers.push(`PyTorch is not importable: ${host.torchProbeError}`);
  const req = requirementsFor(adapter, host);
  if (req && !req.fitsInHostRam_bf16) {
    blockers.push(`host RAM ${req.hostRamTotalGb} GB is below the ${req.weightsInMemoryGb_bf16} GB `
      + `the base model needs in BF16 before any cache or activations`);
  }
  if (!loraEnabled()) {
    blockers.push('the LoRA provider is disabled (INSAF_LORA_ENABLED is not set to 1)');
  }

  const value = {
    // --- what is actually producing the answer text ---
    activeGenerationProvider: 'deterministic-corpus-composer (server/ownedModel.js)',
    generationEngine: 'rule-based composition over retrieved corpus records; no neural generation in the request path',
    neuralGenerationInRequestPath: YESNO(loraEnabled() && inference.passed === 'YES'),
    externalLlmCalls: 'NONE',
    // --- the adapter on disk ---
    fineTunedAdapterPresent: YESNO(!!adapter),
    adapters: adapters.map(a => ({
      dir: a.dir,
      baseModel: a.baseModel || null,
      weights: a.weightFile ? `${a.weightFile} (${a.weightBytes.toLocaleString('en-US')} bytes)` : 'none',
      realWeights: YESNO(a.weightBytes > 0),
      tensors: a.tensors,
      parameters: a.parameters,
      dtypes: a.dtypes,
      rank: a.rank,
      alpha: a.alpha,
      peftVersion: a.peftVersion,
      tokenizerFiles: a.tokenizerFiles,
      readmeOnly: a.readmeOnly,
    })),
    // --- the base model those weights need ---
    baseModel: adapter ? adapter.baseModel : null,
    baseModelRevision: adapter ? adapter.baseRevision : null,
    baseModelRevisionPinned: YESNO(!!(adapter && adapter.baseRevision)),
    baseModelWeightsPresentLocally: YESNO(baseWeightsPresent),
    baseModelCache: {
      cacheDir: String(cache.cacheDir || '').replace(/\\/g, '/'),
      snapshotDirs: cache.snapshots,
      weightFiles: cache.weightFiles,
      weightBytes: cache.bytes,
    },
    baseModelLoaded: YESNO(!!(service && service.modelLoaded)),
    // --- the adapter in memory ---
    adapterLoaded: YESNO(!!(service && service.modelLoaded)),
    providerEnabled: YESNO(loraEnabled()),
    serviceConfigured: YESNO(loraServiceConfigured()),
    inferenceTest: { attempted: inference.attempted, passed: inference.passed, reason: inference.reason },
    // --- host reality ---
    host,
    requirements: req,
    // --- honest summary ---
    fineTunedModelInUse: 'NO',
    lastModelLoadError: blockers.length ? blockers.join('; ') : null,
    blockers,
  };

  // `trained but never served` is the true state here: real weights exist and
  // nothing has ever generated text with them in this application.
  if (adapter && value.fineTunedModelInUse !== 'YES') value.state = 'adapter trained, not served';
  else if (adapter) value.state = 'serving';
  else value.state = 'no adapter';

  cached = { at: Date.now(), value };
  return value;
}

/** Redacted for callers that are not the operator: no paths, no host inventory. */
export function publicModelStatus(status) {
  return {
    fineTunedAdapterPresent: status.fineTunedAdapterPresent,
    adapterLoaded: status.adapterLoaded,
    baseModelLoaded: status.baseModelLoaded,
    inferenceTestPassed: status.inferenceTest.passed,
    fineTunedModelInUse: status.fineTunedModelInUse,
    generationEngine: status.activeGenerationProvider,
    lastModelLoadError: status.blockers.length
      ? `${status.blockers.length} requirement(s) unmet — the list is withheld until the operator sets INSAF_HEALTH_VERBOSE=1`
      : null,
  };
}

export function clearModelStatusCache() { cached = null; }
